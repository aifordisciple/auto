def generate_readme_autonome_md(
    output_path: str,
    task_id: str,
    skill_name: str,
    user_message: str,
    docker_image: str,
    entry_point: str,
    parameters: Dict[str, Any],
    timestamp: Union[str, datetime],
    semantic_dir_name: Optional[str] = None,
    project_id: Optional[str] = None,
    executor_type: str = "Python_env",
    duration: Optional[float] = None,
    skill_repo: Optional[str] = None,
    skill_license: str = "MIT",
    version: str = "1.0.0",
    input_paths: Optional[List[str]] = None,
    output_paths: Optional[List[str]] = None,
) -> str:
    """
    生成 README_autonome.md 文件

    Args:
        output_path: 输出文件路径
        task_id: 任务 ID
        skill_name: 技能名称
        user_message: 用户原始意图
        docker_image: Docker 镜像名称
        entry_point: 入口脚本
        parameters: 执行参数
        timestamp: 执行时间
        semantic_dir_name: 语义化目录名
        project_id: 项目 ID
        executor_type: 执行器类型
        duration: 执行时长（秒）
        skill_repo: 技能仓库地址
        skill_license: 技能许可证
        version: Autonome 版本
        input_paths: 输入文件路径列表
        output_paths: 输出文件路径列表

    Returns:
        生成的文件路径
    """
    # 格式化时间戳
    if isinstance(timestamp, datetime):
        timestamp_str = timestamp.strftime("%Y-%m-%d %H:%M:%S")
    else:
        timestamp_str = str(timestamp)

    # 格式化执行时长
    if duration:
        duration_str = f"{duration:.2f}s"
    else:
        duration_str = "N/A"

    # 生成参数表格
    parameters_table = _generate_parameters_table(parameters)

    # 生成 IO 表格
    io_table = _generate_io_table(input_paths, output_paths)

    # 生成 CLI 参数
    cli_args = _generate_cli_args(parameters)

    # 生成 README 内容
    content = README_TEMPLATE.format(
        task_id=task_id,
        semantic_dir_name=semantic_dir_name or task_id[:8],
        skill_name=skill_name,
        executor_type=executor_type,
        timestamp=timestamp_str,
        project_id=project_id or "N/A",
        user_message=user_message or "No user message provided",
        docker_image=docker_image,
        entry_point=entry_point,
        execution_mode=executor_type,
        duration=duration_str,
        parameters_table=parameters_table,
        io_table=io_table,
        skill_repo=skill_repo or "https://github.com/autonome/skills",
        cli_args=cli_args,
        skill_license=skill_license,
        version=version,
        generated_at=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    )

    # 写入文件
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)

    log.info(f"Generated README_autonome.md: {output_path}")
    return output_path


def _generate_parameters_table(parameters: Dict[str, Any]) -> str:
    """生成 Markdown 参数表格"""
    rows = []
    for key, value in parameters.items():
        if key.startswith("_") or key in ["message", "user_message"]:
            continue
        if value is None:
            continue

        ptype = _infer_type(value)
        value_str = str(value)[:100]  # 截断长值

        rows.append(f"| `{key}` | `{value_str}` | {ptype} |")

    return "\n".join(rows) if rows else "| - | - | - |"


def _generate_io_table(
    input_paths: Optional[List[str]],
    output_paths: Optional[List[str]],
) -> str:
    """生成 Markdown IO 表格"""
    rows = []

    if input_paths:
        for path in input_paths:
            rows.append(f"| Input | `{path}` |")

    if output_paths:
        for path in output_paths:
            rows.append(f"| Output | `{path}` |")

    return "\n".join(rows) if rows else "| - | - |"


def _generate_cli_args(parameters: Dict[str, Any]) -> str:
    """生成 CLI 参数字符串"""
    args = []
    for key, value in parameters.items():
        if key.startswith("_") or key in ["message", "user_message", "PROJECT_ID", "TASK_ID"]:
            continue
        if value is None:
            continue

        # 格式化为 --key value
        key_arg = key.replace("_", "-")
        args.append(f"--{key_arg} {value}")

    return " \\\n  ".join(args) if args else ""


