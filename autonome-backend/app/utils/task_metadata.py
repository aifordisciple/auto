# ============================================================================
# 核心函数：生成 run_parameters.tsv
# ============================================================================

def generate_run_parameters_tsv(
    output_path: str,
    parameters: Dict[str, Any],
    execution_context: Dict[str, Any],
    skill_metadata: Optional[Dict[str, Any]] = None,
) -> str:
    """
    生成 run_parameters.tsv 文件

    Args:
        output_path: 输出文件路径
        parameters: 用户输入参数
        execution_context: 执行上下文（task_id, project_id, timestamp 等）
        skill_metadata: 技能元数据（可选）

    Returns:
        生成的文件路径

    TSV Format:
        parameter    value    type    source
        sample_sheet    ./sample.tsv    filepath    user_input
        threads    8    integer    config
    """
    rows: List[List[str]] = [TSV_HEADERS]

    # 1. 添加执行上下文
    context_rows = _format_context_rows(execution_context)
    rows.extend(context_rows)

    # 2. 添加用户参数
    param_rows = _format_parameter_rows(parameters)
    rows.extend(param_rows)

    # 3. 添加技能元数据
    if skill_metadata:
        skill_rows = _format_skill_rows(skill_metadata)
        rows.extend(skill_rows)

    # 写入文件
    _write_tsv(output_path, rows)

    log.info(f"Generated run_parameters.tsv: {output_path}")
    return output_path


def _format_context_rows(context: Dict[str, Any]) -> List[List[str]]:
    """格式化执行上下文为 TSV 行"""
    rows = []

    # 标准上下文字段
    context_fields = [
        ("Task_ID", context.get("task_id", ""), "string", "system"),
        ("Semantic_Dir", context.get("semantic_dir_name", ""), "string", "system"),
        ("Project_ID", context.get("project_id", ""), "string", "system"),
        ("Execution_Time", context.get("timestamp", ""), "datetime", "system"),
        ("Duration_Seconds", context.get("duration", ""), "integer", "system"),
    ]

    for param, value, ptype, source in context_fields:
        if value:
            rows.append([param, str(value), ptype, source])

    return rows


def _format_parameter_rows(parameters: Dict[str, Any]) -> List[List[str]]:
    """格式化用户参数为 TSV 行"""
    rows = []

    for key, value in parameters.items():
        # 跳过内部参数
        if key.startswith("_") or key in ["message", "user_message"]:
            continue

        # 推断类型
        ptype = _infer_type(value)
        source = "user_input"

        # 处理特殊值
        if isinstance(value, (list, dict)):
            value = str(value)[:200]  # 截断长值
        elif value is None:
            continue

        rows.append([key, str(value), ptype, source])

    return rows


def _format_skill_rows(metadata: Dict[str, Any]) -> List[List[str]]:
    """格式化技能元数据为 TSV 行"""
    rows = []

    skill_fields = [
        ("Skill_ID", metadata.get("skill_id", ""), "string", "skill"),
        ("Skill_Name", metadata.get("name", ""), "string", "skill"),
        ("Skill_Version", metadata.get("version", ""), "string", "skill"),
        ("Executor_Type", metadata.get("executor_type", ""), "string", "skill"),
        ("Entry_Point", metadata.get("entry_point", ""), "string", "skill"),
        ("Docker_Image", metadata.get("docker_image", ""), "string", "skill"),
    ]

    for param, value, ptype, source in skill_fields:
        if value:
            rows.append([param, str(value), ptype, source])

    return rows


def _infer_type(value: Any) -> str:
    """推断参数类型"""
    if isinstance(value, bool):
        return "boolean"
    elif isinstance(value, int):
        return "integer"
    elif isinstance(value, float):
        return "float"
    elif isinstance(value, str):
        # 检查是否是文件路径
        if "/" in value or value.startswith("./") or value.endswith((".tsv", ".csv", ".fastq", ".bam")):
            return "filepath"
        return "string"
    elif isinstance(value, list):
        return "array"
    elif isinstance(value, dict):
        return "object"
    return "unknown"


def _write_tsv(path: str, rows: List[List[str]]) -> None:
    """写入 TSV 文件"""
    # 确保目录存在
    os.makedirs(os.path.dirname(path), exist_ok=True)

    with open(path, "w", encoding="utf-8") as f:
        for row in rows:
            # TSV 使用制表符分隔
            line = "\t".join(row)
            f.write(line + "\n")


