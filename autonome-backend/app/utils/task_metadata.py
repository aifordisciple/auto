def inject_metadata_files(
    output_dir: str,
    task_id: str,
    skill_id: str,
    skill_name: str,
    user_message: str,
    parameters: Dict[str, Any],
    docker_image: str,
    entry_point: str,
    timestamp: Union[str, datetime],
    semantic_dir_name: Optional[str] = None,
    project_id: Optional[str] = None,
    executor_type: str = "Python_env",
    duration: Optional[float] = None,
    skill_metadata: Optional[Dict[str, Any]] = None,
    input_paths: Optional[List[str]] = None,
    output_paths: Optional[List[str]] = None,
) -> Dict[str, str]:
    """
    一键生成所有元数据文件

    Args:
        output_dir: 输出目录
        其他参数同上

    Returns:
        生成的文件路径字典
    """
    # 确保输出目录存在
    os.makedirs(output_dir, exist_ok=True)

    # 准备执行上下文
    execution_context = {
        "task_id": task_id,
        "semantic_dir_name": semantic_dir_name,
        "project_id": project_id,
        "timestamp": timestamp,
        "duration": duration,
    }

    # 准备技能元数据
    if skill_metadata is None:
        skill_metadata = {
            "skill_id": skill_id,
            "name": skill_name,
            "executor_type": executor_type,
            "entry_point": entry_point,
            "docker_image": docker_image,
        }

    # 生成 run_parameters.tsv
    tsv_path = os.path.join(output_dir, "run_parameters.tsv")
    generate_run_parameters_tsv(
        output_path=tsv_path,
        parameters=parameters,
        execution_context=execution_context,
        skill_metadata=skill_metadata,
    )

    # 生成 README_autonome.md
    readme_path = os.path.join(output_dir, "README_autonome.md")
    generate_readme_autonome_md(
        output_path=readme_path,
        task_id=task_id,
        skill_name=skill_name,
        user_message=user_message,
        docker_image=docker_image,
        entry_point=entry_point,
        parameters=parameters,
        timestamp=timestamp,
        semantic_dir_name=semantic_dir_name,
        project_id=project_id,
        executor_type=executor_type,
        duration=duration,
        input_paths=input_paths,
        output_paths=output_paths,
    )

    log.info(f"Injected metadata files into: {output_dir}")

    return {
        "run_parameters_tsv": tsv_path,
        "readme_md": readme_path,
    }